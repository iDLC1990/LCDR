/* Диагонали: единая таблица для «Statistic per day» (livedata.js) и «Statistic» (statistic.js).
   Новую модель добавляют здесь, в одном месте.
   Подключение: <script src="js/diagonals.js"></script> ПЕРЕД livedata.js и statistic.js. */
(function () {
  // Первые 3 символа серийного номера -> диагональ
  const PREFIX = {
    '3P0': 65, '3H0': 55, 'WP0': 65, 'WP5': 65, '3M0': 50, '3Q0': 43, 'WQ0': 43, '3C0': 32, 'WC0': 32, 'WH8': 55,
    'WH0': 55, 'WM0': 50, 'WC8': 32, 'WU0': 43, 'SQ1': 43, 'WM5': 50, 'WC7': 32, 'WW1': 75, 'WM6': 50
  };

  // Три цифры размера в серийном номере -> диагональ
  const SUFFIX = {
    '860': 86, '850': 85, '750': 75, '700': 70, '650': 65, '580': 58, '575': 58,
    '550': 55, '545': 55, '500': 50, '498': 50, '495': 50, '490': 50,
    '438': 43, '435': 43, '430': 43, '428': 43, '425': 43, '420': 43,
    '418': 43, '415': 43, '398': 43, '395': 43, '390': 43,
    '348': 32, '345': 32, '340': 32, '328': 32, '325': 32, '320': 32,
    '318': 32, '315': 32, '278': 27, '275': 27, '270': 27,
    '248': 24, '245': 24, '240': 24, '238': 24, '235': 24, '230': 24
  };

  // Серийный номер -> диагональ или null.
  // Порядок: префикс, затем цифры на позициях 4-6, затем последние 3 символа.
  function fromSerial(serial) {
    if (!serial) return null;
    const s = String(serial).trim().toUpperCase();
    if (s.length < 6) return null;
    return PREFIX[s.slice(0, 3)] || SUFFIX[s.slice(3, 6)] || SUFFIX[s.slice(-3)] || null;
  }

  window.LCDR_DIAG = { PREFIX, SUFFIX, fromSerial };
})();
